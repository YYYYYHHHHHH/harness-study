import { resolve } from 'node:path';
import type { ChatCompletionFunctionTool, ChatCompletionUserMessageParam } from 'openai/resources/chat/completions';

export const MAIN_AGENT_NAME = 'main';
export const INBOX_DIRECTORY = '.teammates_inbox';
export const IDLE_POLL_INTERVAL_MS = 1000;

// An absolute end assertion also rejects a trailing newline (unlike JS `$`).
export const AGENT_NAME_PATTERN = '^[a-z][a-z0-9_-]{0,63}(?![\\s\\S])';
const reservedFileNames = ['con', 'prn', 'aux', 'nul',
  ...Array.from({ length: 10 }, (_, i) => `com${i}`),
  ...Array.from({ length: 10 }, (_, i) => `lpt${i}`)];
const nameSchema = { type: 'string', pattern: AGENT_NAME_PATTERN, not: { enum: reservedFileNames } };
const nonblankSchema = { type: 'string', pattern: '\\S' };

export interface TeammateSpec { name: string; prompt: string }
export interface SpawnTeammatesArgs { teammates: TeammateSpec[] }
export interface SendMessageArgs { sender: string; target: string; content: string }
export interface TeamMessage extends SendMessageArgs {
  /** Generated by the bus, unique within the workspace. Never supplied by the model. */
  id: string;
  /** UTC ISO 8601, e.g. 2026-10-29T00:00:00.000Z; ordering uses append order. */
  created_at: string;
}

/** Tool receipt only; status is not part of the persisted message format. */
export interface SendMessageReceipt extends TeamMessage {
  status: 'queued';
}

/** Runtime-owned inputs. Never construct this identity from tool arguments. */
export interface MessageValidationContext {
  agentName: string;
  /** Registered, accepting recipients, including main. */
  knownAgents: ReadonlySet<string>;
}

/** Shared protocol schemas, registered by the tools module. */
export const teamToolSchemas: ChatCompletionFunctionTool[] = [
  { type: 'function', function: {
    name: 'spawn_teammates', description: '主 agent 批量创建常驻 teammate；名称在工作区团队内唯一。',
    parameters: { type: 'object', additionalProperties: false, required: ['teammates'], properties: {
      teammates: { type: 'array', minItems: 1, items: {
        type: 'object', additionalProperties: false, required: ['name', 'prompt'], properties: {
          name: { ...nameSchema, not: { enum: [...reservedFileNames, MAIN_AGENT_NAME] } },
          prompt: nonblankSchema,
        },
      } },
    } },
  } },
  { type: 'function', function: {
    name: 'send_message', description: '向已注册的 agent 投递消息；sender 必须与运行时身份一致。成功只表示已持久化入队。',
    parameters: { type: 'object', additionalProperties: false, required: ['sender', 'target', 'content'], properties: {
      sender: nameSchema, target: nameSchema, content: nonblankSchema,
    } },
  } },
];

function objectWithKeys(value: unknown, keys: readonly string[], label: string): Record<string, unknown> {
  if (typeof value !== 'object' || value === null || Array.isArray(value)) {
    throw new Error(`${label} 必须是对象`);
  }
  const object = value as Record<string, unknown>;
  for (const key of Object.keys(object)) {
    if (!keys.includes(key)) throw new Error(`${label} 未知字段：${key}`);
  }
  for (const key of keys) {
    if (!Object.hasOwn(object, key)) throw new Error(`${label} 缺少字段：${key}`);
  }
  return object;
}

function nonblank(value: unknown, label: string): string {
  if (typeof value !== 'string' || !value.trim()) throw new Error(`${label} 必须是非空字符串`);
  return value;
}

export function parseAgentName(value: unknown): string {
  if (typeof value !== 'string' || !new RegExp(AGENT_NAME_PATTERN).test(value) || reservedFileNames.includes(value)) {
    throw new Error('agent 名称必须是安全文件名：1–64 位小写字母、数字、下划线或连字符，以字母开头，且不是设备保留名');
  }
  return value;
}

/** Pure preflight; the runtime must repeat this under its registry reservation lock. */
export function parseSpawnTeammatesArgs(value: unknown, existingNames: ReadonlySet<string> = new Set()): SpawnTeammatesArgs {
  const args = objectWithKeys(value, ['teammates'], 'spawn_teammates');
  if (!Array.isArray(args.teammates) || args.teammates.length === 0) throw new Error('teammates 必须是非空数组');
  const names = new Set(existingNames);
  names.add(MAIN_AGENT_NAME);
  const teammates = args.teammates.map((item, index) => {
    const spec = objectWithKeys(item, ['name', 'prompt'], `teammates[${index}]`);
    const name = parseAgentName(spec.name);
    if (names.has(name)) throw new Error(`agent 名称已占用：${name}`);
    names.add(name);
    return { name, prompt: nonblank(spec.prompt, 'prompt') };
  });
  return { teammates };
}

export function parseSendMessageArgs(value: unknown, context: MessageValidationContext): SendMessageArgs {
  const args = objectWithKeys(value, ['sender', 'target', 'content'], 'send_message');
  const sender = parseAgentName(args.sender);
  const target = parseAgentName(args.target);
  if (sender !== context.agentName || !context.knownAgents.has(sender)) throw new Error('sender 与运行时身份不匹配');
  if (!context.knownAgents.has(target)) throw new Error(`未知或不接收消息的目标：${target}`);
  return { sender: context.agentName, target, content: nonblank(args.content, 'content') };
}

/** Structural disk validation does not authenticate the sender of an existing file. */
export function parseTeamMessage(value: unknown): TeamMessage {
  const record = objectWithKeys(value, ['id', 'sender', 'target', 'content', 'created_at'], 'TeamMessage');
  const created_at = nonblank(record.created_at, 'created_at');
  const date = new Date(created_at);
  if (!Number.isFinite(date.getTime()) || date.toISOString() !== created_at) throw new Error('created_at 必须是 UTC ISO 时间');
  return {
    id: nonblank(record.id, 'id'), sender: parseAgentName(record.sender), target: parseAgentName(record.target),
    content: nonblank(record.content, 'content'), created_at,
  };
}

/** Exactly one physical line, even when content contains newlines. */
export function encodeInboxMessage(message: TeamMessage): string {
  return JSON.stringify(parseTeamMessage(message)) + '\n';
}

/** Accept one line without its delimiter; malformed lines must not be discarded. */
export function decodeInboxMessage(line: string): TeamMessage {
  if (/[\r\n]/.test(line)) throw new Error('JSONL 解码一次只接受一行，不含行分隔符');
  return parseTeamMessage(JSON.parse(line));
}

/** Lexical path only. The storage layer must reject symlink directories/files. */
export function inboxPath(workspace: string, agentName: string): string {
  return resolve(workspace, INBOX_DIRECTORY, `${parseAgentName(agentName)}.jsonl`);
}

/** Keep metadata and untrusted content as separate JSON fields in a user event. */
export function teamMessageToUserEvent(message: TeamMessage): ChatCompletionUserMessageParam {
  return { role: 'user', content: JSON.stringify({ type: 'team_message', message: parseTeamMessage(message) }) };
}
